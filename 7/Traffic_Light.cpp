#include <bits/stdc++.h>
using namespace std;

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    char c;
    cin >> c;

    if (c == 'B')
    {
        cout << "Y" << endl;
    }
    else if (c == 'Y')
    {
        cout << "R" << endl;
    }
    else
    {
        cout << "B" << endl;
    }

    return 0;
}